namespace NTiInbox.SystemApis;

/// <summary>
/// Message of a message queue, as returned by QMHLSTM (LSTM0100 format).
/// Fields tagged with an id in parentheses are filled from the variable fields
/// requested in the call.
/// </summary>
public class QueueMessage
{
    /// <summary>Message severity, 0 to 99.</summary>
    public int MessageSeverity { get; set; }

    /// <summary>Message id, for example CPF9898. Empty for an immediate message.</summary>
    public string? MessageId { get; set; }

    /// <summary>Two-character message type: 01 completion, 02 diagnostic, 04 information, 05 request...</summary>
    public string? MessageType { get; set; }

    /// <summary>Unique 4-byte key of the message in the queue. Used to reply and to remove.</summary>
    public byte[]? MessageKey { get; set; }

    /// <summary>Name of the associated message file.</summary>
    public string? MessageFileName { get; set; }

    /// <summary>Message file library specified at send time.</summary>
    public string? MessageFileLibrarySpecified { get; set; }

    /// <summary>Name of the message queue the message comes from.</summary>
    public string? MessageQueue { get; set; }

    /// <summary>Library of the message queue.</summary>
    public string? MessageLibrary { get; set; }

    /// <summary>Send date, converted to yyyy-MM-dd.</summary>
    public string? DateSent { get; set; }

    /// <summary>Send time, converted to HH:mm:ss.</summary>
    public string? TimeSent { get; set; }

    /// <summary>Microseconds of the send time.</summary>
    public string? Microseconds { get; set; }

    /// <summary>Time zone abbreviation at send time.</summary>
    public string? TimeZoneAbbreviation { get; set; }

    /// <summary>Alert option (0101).</summary>
    public string? AlertOption { get; set; }

    /// <summary>Substitution data or text of the immediate message (0201).</summary>
    public string? ReplacementData { get; set; }

    /// <summary>Message text without substitution (0301).</summary>
    public string? MessageText { get; set; }

    /// <summary>Message text with substitution data applied (0302).</summary>
    public string? MessageWithReplacementData { get; set; }

    /// <summary>Message help (0401).</summary>
    public string? MessageHelp { get; set; }

    /// <summary>Message help with substitution (0402).</summary>
    public string? MessageHelpWithReplacementData { get; set; }

    /// <summary>Message help with formatting characters (0403).</summary>
    public string? MessageHelpWithFormatting { get; set; }

    /// <summary>Default reply offered for an inquiry message (0501).</summary>
    public string? DefaultReply { get; set; }

    /// <summary>Sender job, in name/user/number form (0601).</summary>
    public string? SenderJob { get; set; }

    /// <summary>Sender type (0602).</summary>
    public string? SenderType { get; set; }

    /// <summary>Sending program name (0603).</summary>
    public string? SendingProgramName { get; set; }

    /// <summary>Sending module name (0604).</summary>
    public string? SendingModuleName { get; set; }

    /// <summary>Sending procedure name (0605).</summary>
    public string? SendingProcedureName { get; set; }

    /// <summary>User profile that sent the message (0607).</summary>
    public string? SenderUserProfile { get; set; }

    /// <summary>Receiving type (0702).</summary>
    public string? ReceivingType { get; set; }

    /// <summary>Receiving program name (0703).</summary>
    public string? ReceivingProgramName { get; set; }

    /// <summary>Receiving module name (0704).</summary>
    public string? ReceivingModuleName { get; set; }

    /// <summary>Receiving procedure name (0705).</summary>
    public string? ReceivingProcedureName { get; set; }

    /// <summary>Message file library actually used (0801).</summary>
    public string? MessageFileLibraryUsed { get; set; }

    /// <summary>Problem id generated by the system (0901).</summary>
    public string? ProblemId { get; set; }

    /// <summary>
    /// Reply status (1001). A: a reply was sent,
    /// W: the message waits for a reply, N: no reply expected.
    /// </summary>
    public string? ReplyStatus { get; set; }

    /// <summary>Critical break status (1002). 1: critical, 0: normal.</summary>
    public string? CriticalBreakStatus { get; set; }

    /// <summary>Status of the request tied to the message (1101).</summary>
    public string? RequestStatus { get; set; }

    /// <summary>Level of the request tied to the message (1201).</summary>
    public int RequestLevel { get; set; }

    /// <summary>CCSID used for the message text (1301).</summary>
    public int CCSID { get; set; }

    /// <summary>CCSID conversion status of the text (1302).</summary>
    public int CCSIDConversionStatusText { get; set; }

    /// <summary>CCSID used for the message data (1303).</summary>
    public int CCSIDData { get; set; }

    /// <summary>CCSID conversion status of the data (1304).</summary>
    public int CCSIDConversionStatusData { get; set; }
}
